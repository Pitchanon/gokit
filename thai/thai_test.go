package thai

import (
	"math"
	"testing"
	"time"
)

func TestBahtText(t *testing.T) {
	for _, tc := range []struct {
		amt  float64
		want string
	}{
		{0, "ศูนย์บาทถ้วน"},
		{1, "หนึ่งบาทถ้วน"},
		{10, "สิบบาทถ้วน"},
		{11, "สิบเอ็ดบาทถ้วน"},
		{20, "ยี่สิบบาทถ้วน"},
		{21, "ยี่สิบเอ็ดบาทถ้วน"},
		{101, "หนึ่งร้อยหนึ่งบาทถ้วน"},
		{111, "หนึ่งร้อยสิบเอ็ดบาทถ้วน"},
		{143, "หนึ่งร้อยสี่สิบสามบาทถ้วน"},
		{1000000, "หนึ่งล้านบาทถ้วน"},
		{1000001, "หนึ่งล้านหนึ่งบาทถ้วน"},
		{11000000, "สิบเอ็ดล้านบาทถ้วน"},
		{1234567, "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทถ้วน"},
		{1000000000000, "หนึ่งล้านล้านบาทถ้วน"},
		{1000001000000, "หนึ่งล้านหนึ่งล้านบาทถ้วน"},
		{0.5, "ห้าสิบสตางค์"},
		{0.25, "ยี่สิบห้าสตางค์"},
		{0.01, "หนึ่งสตางค์"},
		{143.50, "หนึ่งร้อยสี่สิบสามบาทห้าสิบสตางค์"},
		{1.01, "หนึ่งบาทหนึ่งสตางค์"},
		{1.11, "หนึ่งบาทสิบเอ็ดสตางค์"},
		{1.005, "หนึ่งบาทถ้วน"}, // 1.005 is 1.00499… in binary, %.2f rounds down
		{999999999.99, "เก้าร้อยเก้าสิบเก้าล้านเก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทเก้าสิบเก้าสตางค์"},
		{-21.5, "ลบยี่สิบเอ็ดบาทห้าสิบสตางค์"},
		{-0.001, "ศูนย์บาทถ้วน"},
		{math.NaN(), ""},
		{math.Inf(1), ""},
	} {
		if got := BahtText(tc.amt); got != tc.want {
			t.Errorf("BahtText(%v) = %q, want %q", tc.amt, got, tc.want)
		}
	}
}

func TestDateThai(t *testing.T) {
	d := time.Date(2026, 7, 22, 0, 0, 0, 0, time.UTC)
	if got := DateThai(d); got != "22 ก.ค. 2569" {
		t.Errorf("DateThai = %q", got)
	}
	if got := DateThaiLong(d); got != "22 กรกฎาคม 2569" {
		t.Errorf("DateThaiLong = %q", got)
	}
	if got := DateThai(time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)); got != "1 ม.ค. 2569" {
		t.Errorf("DateThai = %q", got)
	}
	if got := DateThai(time.Date(2026, 12, 31, 0, 0, 0, 0, time.UTC)); got != "31 ธ.ค. 2569" {
		t.Errorf("DateThai = %q", got)
	}
	if DateThai(time.Time{}) != "" || DateThaiLong(time.Time{}) != "" {
		t.Error("zero time must give an empty string")
	}
}
